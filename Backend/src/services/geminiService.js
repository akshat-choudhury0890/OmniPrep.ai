import { z } from 'zod';
import { AppError } from '../utils/errors.js';
import { ANSWER_SCHEMA, CONDENSE_SYSTEM_INSTRUCTION } from './prompts.js';
import { GeminiError, runWithTimeout } from './geminiClient.js';

const BLOCK_REASONS = new Set(['SAFETY', 'PROHIBITED_CONTENT', 'BLOCKLIST', 'SPII', 'IMAGE_SAFETY']);

const answerShape = z.object({
  evidence_status: z.enum(['supported', 'partial', 'insufficient']),
  answer: z.string().trim().min(1),
  used_sources: z.array(z.string()).default([]),
});

function parseAnswer(res, model) {
  const blockReason = res?.promptFeedback?.blockReason;
  const finish = res?.candidates?.[0]?.finishReason;
  if (blockReason || BLOCK_REASONS.has(finish)) {
    throw new GeminiError('blocked', `Response blocked (${blockReason ?? finish})`, { retryable: false, model });
  }
  let text = res?.text;
  if (!text || !text.trim()) throw new GeminiError('empty_output', 'Model returned no text', { retryable: true, model });

  // Clean markdown code blocks (e.g. ```json ... ```) if returned by Gemini
  text = text.trim().replace(/^```(?:json)?\s*/i, '').replace(/\s*```$/, '').trim();

  let json;
  try {
    json = JSON.parse(text);
  } catch (err) {
    throw new GeminiError('malformed_output', `Model returned invalid JSON: ${err.message}`, { retryable: true, cause: err, model });
  }
  const parsed = answerShape.safeParse(json);
  if (!parsed.success) {
    throw new GeminiError('malformed_output', `Model JSON did not match schema: ${parsed.error.message}`, { retryable: true, model });
  }
  return parsed.data;
}

function toAppError(primaryErr, fallbackErr) {
  const err = fallbackErr ?? primaryErr;
  const kinds = [primaryErr?.kind, fallbackErr?.kind];
  if (kinds.includes('client_aborted')) return new AppError(499, 'CLIENT_CLOSED_REQUEST', 'Request cancelled');
  if (kinds.includes('blocked')) {
    return new AppError(422, 'CONTENT_BLOCKED', 'The AI provider declined to answer this question. Try rephrasing it.', { cause: err });
  }
  if (err?.retryable) {
    return new AppError(503, 'MODEL_UNAVAILABLE', 'The AI models are busy or unreachable right now. Please try again in a moment.', {
      cause: err,
      headers: { 'Retry-After': '10' },
    });
  }
  return new AppError(502, 'AI_PROVIDER_ERROR', 'The AI provider rejected the request. If this keeps happening, contact the site operator.', { cause: err });
}

export function createGeminiService({ config, logger, client }) {
  const log = logger.child({ svc: 'gemini' });

  async function callAnswerModel(model, { systemInstruction, contents }, timeoutMs, parentSignal) {
    const res = await runWithTimeout(
      (signal) =>
        client.models.generateContent({
          model,
          contents,
          config: {
            systemInstruction,
            temperature: 0.2,
            maxOutputTokens: 4096,
            responseMimeType: 'application/json',
            responseSchema: ANSWER_SCHEMA,
            abortSignal: signal,
          },
        }),
      { timeoutMs, parentSignal, model },
    );
    return parseAnswer(res, model);
  }

  async function generateAnswer({ systemInstruction, contents, signal }) {
    const started = Date.now();
    const primary = config.GEMINI_PRIMARY_MODEL;
    const fallback = config.GEMINI_FALLBACK_MODEL;
    let primaryErr;
    try {
      const out = await callAnswerModel(primary, { systemInstruction, contents }, config.GEMINI_TIMEOUT_MS, signal);
      log.info({ model: primary, ms: Date.now() - started, fallbackUsed: false }, 'answer generated');
      return { ...out, modelUsed: primary, fallbackUsed: false };
    } catch (err) {
      primaryErr = err instanceof GeminiError ? err : new GeminiError('unknown', err.message || 'Unexpected error', { cause: err, model: primary });
      log.warn({ model: primary, kind: primaryErr.kind, message: primaryErr.message, status: primaryErr.status, retryable: primaryErr.retryable }, 'primary model failed');
      if (!primaryErr.retryable || fallback === primary) throw toAppError(primaryErr);
    }
    try {
      const out = await callAnswerModel(fallback, { systemInstruction, contents }, config.GEMINI_FALLBACK_TIMEOUT_MS, signal);
      log.info({ model: fallback, ms: Date.now() - started, fallbackUsed: true }, 'answer generated by fallback');
      return { ...out, modelUsed: fallback, fallbackUsed: true };
    } catch (err) {
      const fallbackErr = err instanceof GeminiError ? err : new GeminiError('unknown', err.message || 'Unexpected error', { cause: err, model: fallback });
      log.error({ primary: primaryErr.kind, primaryMsg: primaryErr.message, fallback: fallbackErr.kind, fallbackMsg: fallbackErr.message }, 'both models failed');
      throw toAppError(primaryErr, fallbackErr);
    }
  }

  async function condenseQuestion(history, message, signal) {
    try {
      const contents = [
        ...history.map((m) => ({ role: m.role === 'assistant' ? 'model' : 'user', parts: [{ text: m.content }] })),
        { role: 'user', parts: [{ text: message }] },
      ];
      const res = await runWithTimeout(
        (s) =>
          client.models.generateContent({
            model: config.GEMINI_FALLBACK_MODEL,
            contents,
            config: { systemInstruction: CONDENSE_SYSTEM_INSTRUCTION, temperature: 0, maxOutputTokens: 120, abortSignal: s },
          }),
        { timeoutMs: Math.min(8000, config.GEMINI_FALLBACK_TIMEOUT_MS), parentSignal: signal, model: config.GEMINI_FALLBACK_MODEL },
      );
      const text = res?.text?.trim().replace(/^["']|["']$/g, '');
      return text && text.length <= 400 ? text : message;
    } catch (err) {
      log.warn({ kind: err.kind }, 'question condensing failed; using raw message');
      return message;
    }
  }

  return { generateAnswer, condenseQuestion };
}